/*
 * SPRITES.C -- Authentic Space Invaders arcade pixel data.
 *
 * All bitmaps are read-only tables consumed by CACHE.C during first-run
 * pre-generation.  No hardware access here.
 *
 * Row encoding: bit (w-1) = leftmost pixel, bit 0 = rightmost.
 * Each comment above a row array shows the pixel pattern visually;
 * '.' = off, 'X' = on, columns left-to-right.
 */

#include "SPRITES.H"

/* =========================================================================
 * Bit-field construction helpers (expand as needed for sprite widths)
 *
 * Usage: R11(c0,c1,...,c10) where each arg is 0 or 1 and c0=leftmost.
 * The resulting unsigned int has bit 10=c0, bit 9=c1, ... bit 0=c10.
 * ========================================================================= */
#define B(b,n) ((unsigned int)(b) << (n))

#define R11(a,b,c,d,e,f,g,h,i,j,k) \
    (B(a,10)|B(b,9)|B(c,8)|B(d,7)|B(e,6)|B(f,5)|B(g,4)|B(h,3)|B(i,2)|B(j,1)|B(k,0))

#define R13(a,b,c,d,e,f,g,h,i,j,k,l,m) \
    (B(a,12)|B(b,11)|B(c,10)|B(d,9)|B(e,8)|B(f,7)|B(g,6)|B(h,5)|B(i,4)|B(j,3)|B(k,2)|B(l,1)|B(m,0))

#define R16(a,b,c,d,e,f,g,h,i,j,k,l,m,n,o,p) \
    (B(a,15)|B(b,14)|B(c,13)|B(d,12)|B(e,11)|B(f,10)|B(g,9)|B(h,8)| \
     B(i,7) |B(j,6) |B(k,5) |B(l,4) |B(m,3) |B(n,2) |B(o,1)|B(p,0))

#define R3(a,b,c) (B(a,2)|B(b,1)|B(c,0))

/* Shield rows use unsigned long: 24 bits, bit 23 = leftmost */
#define BL(b,n) ((unsigned long)(b) << (n))
#define R24(a,b,c,d,e,f,g,h,i,j,k,l,m,n,o,p,q,r,s,t,u,v,w,x) \
    (BL(a,23)|BL(b,22)|BL(c,21)|BL(d,20)|BL(e,19)|BL(f,18)| \
     BL(g,17)|BL(h,16)|BL(i,15)|BL(j,14)|BL(k,13)|BL(l,12)| \
     BL(m,11)|BL(n,10)|BL(o,9) |BL(p,8) |BL(q,7) |BL(r,6) | \
     BL(s,5) |BL(t,4) |BL(u,3) |BL(v,2) |BL(w,1) |BL(x,0))

