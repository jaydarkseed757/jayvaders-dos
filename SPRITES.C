/* =========================================================================
 * Access helpers
 * ========================================================================= */

const RawSprite *spr_get(int id) {
    if (id < 0 || id >= SPR_COUNT) return 0;
    return &g_sprites[id];
}

int spr_char_to_glyph(int ch) {
    if (ch >= '0' && ch <= '9') return ch - '0';
    if (ch >= 'A' && ch <= 'Z') return 10 + (ch - 'A');
    if (ch >= 'a' && ch <= 'z') return 10 + (ch - 'a'); /* fold to upper */
    return -1;
}
